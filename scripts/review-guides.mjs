import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pages, metadata } from './validate.mjs';
const wiki = fileURLToPath(new URL('../', import.meta.url));
const docs = path.join(wiki, 'src/content/docs');
const args = process.argv.slice(2);
const rootArg = args.indexOf('--game-root');
const game = path.resolve(rootArg >= 0 ? args[rootArg + 1] : path.join(wiki, '..'));
if (rootArg >= 0) args.splice(rootArg, 2);
const check = args.includes('--check');
const all = args.includes('--all');
const selected = args.filter(a => !a.startsWith('--'));
const recordPath = path.join(wiki, 'src/data/guide-reviews.json');
let records = {};
try { records = JSON.parse(await readFile(recordPath, 'utf8')); } catch (e) { if (e.code !== 'ENOENT') throw e; }
if (!check && !all && !selected.length) throw new Error('Specify reviewed guide paths relative to src/content/docs.');
let stale = 0, reviewed = 0;
for (const file of await pages()) {
  const content = await readFile(file, 'utf8');
  if (content.includes('<!-- Generated by scripts/sync-game.mjs.')) continue;
  const key = path.relative(docs, file).replaceAll('\\', '/');
  if (!check && !all && !selected.includes(key)) continue;
  const sources = metadata(content, file).sources;
  const hash = bytes => createHash('sha256').update(bytes).digest('hex');
  const snapshot = { contentHash: hash(content), sources: Object.fromEntries(await Promise.all(sources.map(async p => [p, hash(await readFile(path.join(game, p)))]))) };
  if (check) {
    if (JSON.stringify(records[key]) !== JSON.stringify(snapshot)) { console.error(`Review guide: ${key}`); stale++; }
  } else { records[key] = snapshot; reviewed++; }
}
if (!check) {
  if (!reviewed) throw new Error('No handwritten guides matched the supplied paths.');
  await writeFile(recordPath, JSON.stringify(records, null, 2) + '\n');
  console.log(`Recorded source review for ${reviewed} guides.`);
} else if (stale) process.exitCode = 1;
else console.log('Handwritten guides match their reviewed source snapshots.');
